"""Write per-suite Turbo and pySHACL counts from the harness and the divergence ledger.

``docs/conformance.json`` holds the counts and the README section between the
conformance markers is rendered from it. Tests fail when either drifts from a
fresh measurement or from the ledger (ADR 0047).
"""

from __future__ import annotations

import json
import logging
import sys
import warnings
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tests"))
from divergence_ledger import Kind, Ledger, Origin, Suite
from w3c_grading import (
    PYSHACL,
    TURBO,
    W3C_SHACL10,
    W3C_SHACL12,
    SuiteTally,
    W3cSuite,
    measure,
)

SUMMARY = ROOT / "docs/conformance.json"
README = ROOT / "README.md"
BEGIN = "<!-- conformance:begin (generated by scripts/conformance_report.py) -->"
END = "<!-- conformance:end -->"
BLOB = "https://github.com/legra-ai/pyshacl-turbo/blob/main"
ADR_LINK = f"{BLOB}/docs/adr/0047-conformance-divergence-ledger.md"
TITLES = {
    Suite.W3C_SHACL10: "W3C SHACL 1.0 (Graph inputs)",
    Suite.W3C_SHACL12: "W3C SHACL 1.2",
    Suite.PYSHACL_UPSTREAM: "pySHACL upstream (non-JS)",
    Suite.DIRECT_CONTRACT: "Direct API/CLI contract",
}


def w3c(suite: W3cSuite) -> dict[str, object]:
    # Reference and suite parsing are noisy for intentionally invalid fixtures.
    logging.disable(logging.CRITICAL)
    try:
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            return SuiteTally.of(measure(suite)).to_json()
    finally:
        logging.disable(logging.NOTSET)


def upstream() -> dict[str, object]:
    turbo = json.loads((ROOT / "docs/upstream-coverage.json").read_text())
    reference = json.loads((ROOT / "docs/upstream-reference.json").read_text())
    origins = Counter(row["origin"] for row in turbo["cases"])
    return {
        "cases": len(turbo["cases"]),
        "origin": dict(sorted(origins.items())),
        "outcomes": {
            TURBO.name: turbo["origin_summary"],
            PYSHACL.name: reference["origin_summary"],
        },
    }


def direct() -> dict[str, object]:
    report = json.loads((ROOT / "docs/direct-contract.json").read_text())
    return {
        "cases": len(report["cases"]),
        "origin": {Origin.FIRST_PARTY.value: len(report["cases"])},
        "versions": {
            "pyshacl": report["reference_version"],
            TURBO.name: report["turbo_version"],
            "rdflib-turbo": report["provider_version"],
        },
        "outcomes": dict(sorted(report["summary"].items())),
    }


def collect() -> dict[str, object]:
    return {
        "schema": 1,
        "ledger": Ledger.load().counts(),
        Suite.W3C_SHACL10.value: w3c(W3C_SHACL10),
        Suite.W3C_SHACL12.value: w3c(W3C_SHACL12),
        Suite.PYSHACL_UPSTREAM.value: upstream(),
        Suite.DIRECT_CONTRACT.value: direct(),
    }


def outcomes(counts: dict[str, int]) -> str:
    return ", ".join(f"{value} {name}" for name, value in counts.items())


def ledger_cell(summary: dict, suite: Suite) -> str:
    counts = summary["ledger"].get(suite.value, {})
    return " / ".join(str(counts.get(kind.value, 0)) for kind in Kind)


def upstream_cell(origins: dict[str, dict[str, int]]) -> str:
    return "; ".join(f"{origin}: {outcomes(counts)}" for origin, counts in origins.items())


def render(summary: dict) -> str:
    rows = [
        "| Suite | Cases | pyshacl-turbo | pySHACL | Ledger intentional / gap |",
        "| --- | --- | --- | --- | --- |",
    ]
    for suite in (Suite.W3C_SHACL10, Suite.W3C_SHACL12):
        data = summary[suite.value]
        rows.append(
            f"| {TITLES[suite]} | {data['cases']} | {outcomes(data['outcomes'][TURBO.name])} "
            f"| {outcomes(data['outcomes'][PYSHACL.name])} | {ledger_cell(summary, suite)} |"
        )
    data = summary[Suite.PYSHACL_UPSTREAM.value]
    rows.append(
        f"| {TITLES[Suite.PYSHACL_UPSTREAM]} | {data['cases']} "
        f"| {upstream_cell(data['outcomes'][TURBO.name])} "
        f"| {upstream_cell(data['outcomes'][PYSHACL.name])} "
        f"| {ledger_cell(summary, Suite.PYSHACL_UPSTREAM)} |"
    )
    data = summary[Suite.DIRECT_CONTRACT.value]
    rows.append(
        f"| {TITLES[Suite.DIRECT_CONTRACT]} | {data['cases']} "
        f"| {outcomes(data['outcomes'])} (compared with pySHACL) | — "
        f"| {ledger_cell(summary, Suite.DIRECT_CONTRACT)} |"
    )
    shacl12 = summary[Suite.W3C_SHACL12.value]
    types = [
        "",
        "W3C SHACL 1.2 by test type (not-run cases are counted, with a typed reason):",
        "",
        "| Type | Cases | pyshacl-turbo | pySHACL |",
        "| --- | --- | --- | --- |",
    ]
    for name, columns in shacl12["types"].items():
        cases = sum(columns[PYSHACL.name].values())
        types.append(
            f"| {name} | {cases} | {outcomes(columns[TURBO.name])} "
            f"| {outcomes(columns[PYSHACL.name])} |"
        )
    relations = outcomes(shacl12["relations"])
    reasons = outcomes(shacl12["not_run"])
    notes = [
        "",
        f"SHACL 1.2 relations to pySHACL: {relations}. Not-run reasons: {reasons}.",
        "Upstream outcomes are split by origin: only vendored cases are upstream",
        "passes; the issue-70 fixture is locally corrected and two cases run",
        "first-party native equivalents. Every difference from pySHACL is listed in",
        f"[tests/divergences.toml]({BLOB}/tests/divergences.toml) ([ADR 0047]({ADR_LINK})).",
    ]
    return "\n".join([BEGIN, *rows, *types, *notes, END])


def readme_section(text: str) -> str:
    start, end = text.index(BEGIN), text.index(END) + len(END)
    return text[start:end]


def main() -> None:
    summary = collect()
    SUMMARY.write_text(json.dumps(summary, indent=2) + "\n")
    text = README.read_text()
    README.write_text(text.replace(readme_section(text), render(summary)))
    print(render(summary))


if __name__ == "__main__":
    main()
